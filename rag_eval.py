JUDGE_SYSTEM = "You are a strict grader of question-answering systems. Reply with JSON only."


def judge(question: str, gold: str, answer: str) -> dict:
    if gold == UNANSWERABLE:
        rule = ("This question is UNANSWERABLE: the information does not exist in the documents. "
                "Reply CORRECT only if the candidate clearly says that the information is not available "
                "or cannot be determined, and does NOT assert any specific answer. "
                "Reply INCORRECT if the candidate states a specific answer, even a plausible one.")
        ref = "(none: the question is unanswerable)"
    else:
        rule = ("Reply CORRECT if the candidate answer states the reference answer. Differences in wording, "
                "number formatting, extra detail and citation markers like [1] are fine. "
                "Reply INCORRECT if it gives a different answer, gives no answer, or says it does not know.")
        ref = gold
    user = (f"Question: {question}\nReference answer: {ref}\nCandidate answer: {answer or '(empty)'}\n\n{rule}\n"
            'Reply exactly as JSON: {"verdict": "CORRECT" or "INCORRECT", "reason": "<one short sentence>"}')
    payload = {"model": JUDGE_MODEL, "temperature": 0, "max_tokens": 800,
               "messages": [{"role": "system", "content": JUDGE_SYSTEM}, {"role": "user", "content": user}]}
    if JUDGE_REASONING:
        payload["reasoning_effort"] = JUDGE_REASONING
    msg, usage, _ = groq_chat(payload)
    text = msg.get("content") or ""

    m = re.search(r'"verdict"\s*:\s*"(CORRECT|INCORRECT)"', text, re.I)
    if m:
        verdict = m.group(1).upper() == "CORRECT"
    elif "INCORRECT" in text.upper():
        verdict = False
    elif "CORRECT" in text.upper():
        verdict = True
    else:
        verdict = None   # judge gave no usable verdict
    r = re.search(r'"reason"\s*:\s*"([^"]*)"', text)
    return {"verdict": verdict, "reason": r.group(1) if r else text[:120].replace("\n", " "),
            "judge_prompt_tokens": usage["prompt_tokens"], "judge_completion_tokens": usage["completion_tokens"]}


