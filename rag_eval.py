def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def generate_corpus_and_questions(seed: int) -> tuple[list[dict], list[dict]]:
    """Return (docs, questions). Same seed -> identical corpus and questions."""
    rng = random.Random(seed)

    labs, cities, projects, fields = LAB_NAMES[:], CITIES[:], PROJECTS[:], FIELDS[:]
    firsts, lasts = FIRST[:], LAST[:]
    for pool in (labs, cities, projects, fields, firsts, lasts):
        rng.shuffle(pool)
    people = [f"{a} {b}" for a, b in zip(firsts, lasts)]           # 24 unique people
    uni_country = {u: rng.choice(COUNTRIES) for u in UNIVERSITIES}

    ents = []
    for i in range(12):
        ents.append({
            "lab": f"{labs[i]} Institute", "city": cities[i], "founder": people[i],
            "year": rng.randint(1950, 2012), "staff": rng.randint(40, 950),
            "project": f"Project {projects[i]}", "field": fields[i], "lead": people[12 + i],
            "samples": f"{rng.randint(10, 990) * 1000:,}", "univ": rng.choice(UNIVERSITIES),
        })

    # ---- documents ----
    docs = []
    doc_id = {}  # (kind, name) -> file name

    def add_doc(kind: str, name: str, text: str):
        fid = f"{kind}_{slug(name)}.txt".replace("project_project_", "project_")
        doc_id[(kind, name)] = fid
        docs.append({"id": fid, "text": text})

    for e in ents:
        f1, f2 = rng.sample(LAB_FILLER, 2)
        add_doc("lab", e["lab"],
                f"The {e['lab']} was founded in {e['year']} by {e['founder']}. "
                f"It is located in the city of {e['city']}. {f1}\n\n"
                f"Today the {e['lab']} employs {e['staff']} researchers. "
                f"Its flagship effort is {e['project']}, which receives most of the institute's attention. {f2}")

        p1, p2 = rng.sample(PROJECT_FILLER, 2)
        add_doc("project", e["project"],
                f"{e['project']} applies machine learning to {e['field']}. "
                f"It is a long-running research effort with a steady team. {p1}\n\n"
                f"The project is led by {e['lead']}. "
                f"The training dataset of {e['project']} contains {e['samples']} samples. {p2}")

        add_doc("person", e["lead"],
                f"{e['lead']} earned a doctorate at {e['univ']}. "
                f"{e['lead']} is known for a clear teaching style and enjoys supervising students. "
                f"The doctoral work of {e['lead']} received positive attention from reviewers.")

    for u in UNIVERSITIES:
        add_doc("university", u, f"{u} is a university in {uni_country[u]}. {rng.choice(UNI_FILLER)}")

    def lab_doc(e): return doc_id[("lab", e["lab"])]
    def proj_doc(e): return doc_id[("project", e["project"])]
    def person_doc(e): return doc_id[("person", e["lead"])]
    def uni_doc(u): return doc_id[("university", u)]

    # ---- questions ----
    questions = []

    def add_q(prefix: str, category: str, kind: str, question: str, gold: str, support: list[str]):
        n = sum(1 for q in questions if q["id"].startswith(prefix)) + 1
        questions.append({"id": f"{prefix}{n}", "category": category, "kind": kind,
                          "question": question, "gold": gold, "support": support})

    # 10 simple: the answer sits in a single document
    s = rng.sample(range(12), 10)
    e = ents[s[0]]; add_q("S", "simple", "lab city", f"In which city is the {e['lab']} located?", e["city"], [lab_doc(e)])
    e = ents[s[1]]; add_q("S", "simple", "lab founder", f"Who founded the {e['lab']}?", e["founder"], [lab_doc(e)])
    e = ents[s[2]]; add_q("S", "simple", "lab year", f"In which year was the {e['lab']} founded?", str(e["year"]), [lab_doc(e)])
    e = ents[s[3]]; add_q("S", "simple", "lab staff", f"How many researchers does the {e['lab']} employ?", str(e["staff"]), [lab_doc(e)])
    e = ents[s[4]]; add_q("S", "simple", "lab flagship", f"What is the flagship project of the {e['lab']}?", e["project"], [lab_doc(e)])
    e = ents[s[5]]; add_q("S", "simple", "project field", f"What field does {e['project']} focus on?", e["field"], [proj_doc(e)])
    e = ents[s[6]]; add_q("S", "simple", "project samples", f"How many samples does the training dataset of {e['project']} contain?", e["samples"], [proj_doc(e)])
    e = ents[s[7]]; add_q("S", "simple", "project lead", f"Who leads {e['project']}?", e["lead"], [proj_doc(e)])
    e = ents[s[8]]; add_q("S", "simple", "person university", f"At which university did {e['lead']} earn a doctorate?", e["univ"], [person_doc(e)])
    u = rng.choice(UNIVERSITIES); add_q("S", "simple", "university country", f"In which country is {u} located?", uni_country[u], [uni_doc(u)])

    # 10 multi-hop: the start entity appears only in the first document; later documents do not mention it
    m = rng.sample(range(12), 10)
    for k in range(3):
        e = ents[m[k]]
        add_q("M", "multi_hop", "lab>project>lead", f"Who leads the flagship project of the {e['lab']}?",
              e["lead"], [lab_doc(e), proj_doc(e)])
    for k in range(3, 5):
        e = ents[m[k]]
        add_q("M", "multi_hop", "lab>project>field", f"What field does the flagship project of the {e['lab']} focus on?",
              e["field"], [lab_doc(e), proj_doc(e)])
    for k in range(5, 7):
        e = ents[m[k]]
        add_q("M", "multi_hop", "project>lead>university", f"At which university did the leader of {e['project']} earn a doctorate?",
              e["univ"], [proj_doc(e), person_doc(e)])
    for k in range(7, 9):
        e = ents[m[k]]
        add_q("M", "multi_hop", "project>lead>university>country",
              f"In which country is the university located where the leader of {e['project']} earned a doctorate?",
              uni_country[e["univ"]], [proj_doc(e), person_doc(e), uni_doc(e["univ"])])
    a = ents[m[9]]
    b = rng.choice([x for x in ents if x["year"] != a["year"] and x is not a])
    first = a if a["year"] < b["year"] else b
    add_q("M", "multi_hop", "compare two labs", f"Which institute was founded earlier, the {a['lab']} or the {b['lab']}?",
          first["lab"], [lab_doc(a), lab_doc(b)])

    # 5 unanswerable: related topic, but the information was never written anywhere
    u_idx = rng.sample(range(12), 4)
    e = ents[u_idx[0]]; add_q("U", "unanswerable", "missing attribute", f"What is the annual budget of the {e['lab']}?", UNANSWERABLE, [])
    e = ents[u_idx[1]]; add_q("U", "unanswerable", "missing attribute", f"Which programming language is {e['project']} written in?", UNANSWERABLE, [])
    e = ents[u_idx[2]]; add_q("U", "unanswerable", "missing attribute", f"Who is the current director of the {e['lab']}?", UNANSWERABLE, [])
    e = ents[u_idx[3]]; add_q("U", "unanswerable", "missing attribute", f"What is the title of the doctoral thesis of {e['lead']}?", UNANSWERABLE, [])
    add_q("U", "unanswerable", "absent entity", "Where is the Zephyrine Institute located?", UNANSWERABLE, [])

    return docs, questions


