# ===========================================================================
def cost_usd(model: str, prompt_tokens: int, completion_tokens: int) -> float:
    p_in, p_out = PRICES.get(model, (0.0, 0.0))
    return prompt_tokens / 1e6 * p_in + completion_tokens / 1e6 * p_out


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% confidence interval for an accuracy of k correct out of n."""
    if n == 0:
        return 0.0, 0.0
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return max(0.0, centre - half), min(1.0, centre + half)


def acc_cell(recs: list[dict]) -> str:
    n = len(recs)
    if n == 0:
        return "-"
    k = sum(1 for r in recs if r["correct"])
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.0f}% [{100 * lo:.0f}-{100 * hi:.0f}]"


def mean(xs: list[float]) -> float:
    return sum(xs) / len(xs) if xs else 0.0


def md_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def build_report(records: list[dict], systems: list[str], seed: int) -> str:
    cats = ["simple", "multi_hop", "unanswerable"]
    by_sys = {s: [r for r in records if r["system"] == s] for s in systems}
    out = [f"# RAG evaluation (seed {seed})", ""]
    out.append(f"Answer model: `{ar.GROQ_MODEL}`  |  Judge model: `{JUDGE_MODEL}`  |  "
               f"Single-shot top-k: {SINGLE_SHOT_K}  |  Agent: max {ar.MAX_STEPS} rounds, {ar.CHUNKS_PER_SEARCH} chunks/search, web search off")
    out.append("")

    # --- accuracy ---
    out += ["## Accuracy (LLM judge; 95% confidence interval in brackets)", ""]
    rows = []
    for s in systems:
        rs = by_sys[s]
        rows.append([s, acc_cell(rs)] + [acc_cell([r for r in rs if r["category"] == c]) for c in cats])
    out.append(md_table(["system", "overall", "simple", "multi-hop", "unanswerable"], rows))
    out.append("")

    # --- latency and cost ---
    out += ["## Latency and token cost (per question, answering model only)", ""]
    rows = []
    for s in systems:
        rs = by_sys[s]
        if not rs:
            continue
        lat = [r["latency_s"] for r in rs]
        tot = [r["latency_total_s"] for r in rs]
        pt = mean([r["prompt_tokens"] for r in rs])
        ct = mean([r["completion_tokens"] for r in rs])
        cost = mean([r["cost_usd"] for r in rs])
        rows.append([s, f"{mean(lat):.1f}", f"{statistics.median(lat):.1f}", f"{mean(tot):.1f}",
                     f"{mean([r['llm_calls'] for r in rs]):.1f}", f"{pt:.0f}", f"{ct:.0f}", f"{pt + ct:.0f}",
                     f"${cost:.5f}", f"${cost * 1000:.2f}"])
    out.append(md_table(["system", "latency mean (s)", "latency median (s)", "incl. rate-limit waits (s)", "LLM calls",
                         "prompt tok", "completion tok", "total tok", "$ / question", "$ / 1,000 questions"], rows))
    out += ["", "Latency excludes time spent sleeping on Groq rate limits (shown separately in the 'incl.' column).", ""]

    # --- by category ---
    out += ["## By question type", ""]
    rows = []
    for s in systems:
        for c in cats:
            rs = [r for r in by_sys[s] if r["category"] == c]
            if rs:
                rows.append([s, c.replace("_", "-"), acc_cell(rs), f"{mean([r['latency_s'] for r in rs]):.1f}",
                             f"{mean([r['prompt_tokens'] + r['completion_tokens'] for r in rs]):.0f}"])
    out.append(md_table(["system", "type", "accuracy", "latency (s)", "total tok"], rows))
    out.append("")

    # --- retrieval support recall ---
    out += ["## Retrieval: were the documents needed for the answer retrieved?", ""]
    rows = []
    for s in systems:
        if s == "closed":
            continue
        for c in ["simple", "multi_hop"]:
            rs = [r for r in by_sys[s] if r["category"] == c and r.get("support_recall") is not None]
            if rs:
                full = sum(1 for r in rs if r["support_recall"] >= 0.999)
                rows.append([s, c.replace("_", "-"), f"{100 * mean([r['support_recall'] for r in rs]):.0f}%", f"{full}/{len(rs)}"])
    if rows:
        out.append(md_table(["system", "type", "avg support recall", "all needed docs retrieved"], rows))
        out.append("")

    # --- overhead notes ---
    judged = [r for r in records if r["system"] in systems]
    jt = sum(r["judge_prompt_tokens"] + r["judge_completion_tokens"] for r in judged)
    jerr = sum(1 for r in judged if r["verdict"] is None)
    jcost = sum(cost_usd(JUDGE_MODEL, r["judge_prompt_tokens"], r["judge_completion_tokens"]) for r in judged)
    wait = sum(r["wait_s"] for r in judged)
    out += ["## Notes", "",
            f"- Judge overhead: {jt:,} tokens (about ${jcost:.4f}); judge calls with no usable verdict (counted as incorrect): {jerr}.",
            f"- Total time spent waiting on rate limits: {wait:.0f}s.",
            "- Prices used (USD per 1M tokens, input/output): "
            + ", ".join(f"{m} {a}/{b}" for m, (a, b) in PRICES.items()) + ". Edit PRICES in rag_eval.py if they change.",
            "- With 5-10 questions per category the confidence intervals are wide: treat differences of one or two questions as noise.",
            ""]
    return "\n".join(out)


