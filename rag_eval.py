CLOSED_SYSTEM = ('Answer the question from your own knowledge. If you do not know the answer or cannot '
                 'verify it, reply exactly: "I don\'t know."')


def _chat_payload(model: str, messages: list[dict], reasoning: str | None) -> dict:
    payload = {"model": model, "messages": messages, "temperature": 0.1, "max_tokens": ar.MAX_OUTPUT_TOKENS}
    if reasoning:
        payload["reasoning_effort"] = reasoning
    return payload


def run_closed_book(question: str) -> dict:
    t0 = time.perf_counter()
    msg, usage, waited = groq_chat(_chat_payload(
        ar.GROQ_MODEL,
        [{"role": "system", "content": CLOSED_SYSTEM}, {"role": "user", "content": question}],
        ar.REASONING_EFFORT))
    return _result(msg.get("content") or "", t0, waited, usage, calls=1, tools=[], docs=[])


def run_single_shot(kb, question: str) -> dict:
    t0 = time.perf_counter()
    retrieved = retrieve(kb, question, SINGLE_SHOT_K)
    msg, usage, waited = groq_chat(_chat_payload(
        ar.GROQ_MODEL, build_single_shot_messages(question, retrieved), ar.REASONING_EFFORT))
    return _result(msg.get("content") or "", t0, waited, usage, calls=1, tools=[],
                   docs=sorted({r["source"] for r in retrieved}))


def run_agentic(agent: AgenticRAG, question: str) -> dict:
    t0 = time.perf_counter()
    answer = agent.ask(question, verbose=False)
    s = agent.stats
    usage = {"prompt_tokens": s["prompt_tokens"], "completion_tokens": s["completion_tokens"]}
    return _result(answer, t0, s["wait_s"], usage, calls=s["llm_calls"], tools=list(s["tool_calls"]),
                   docs=sorted({e["source"] for e in agent.evidence}))


def _result(answer: str, t0: float, waited: float, usage: dict, calls: int, tools: list, docs: list) -> dict:
    total = time.perf_counter() - t0
    return {
        "answer": answer.strip(),
        "latency_total_s": round(total, 3),
        "wait_s": round(waited, 3),                       # time spent sleeping on rate limits
        "latency_s": round(max(total - waited, 0), 3),    # latency without the rate-limit sleeps
        "prompt_tokens": usage["prompt_tokens"],
        "completion_tokens": usage["completion_tokens"],
        "llm_calls": calls,
        "tool_calls": tools,
        "retrieved_docs": docs,
    }


