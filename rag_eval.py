"""
Automated evaluation: closed-book vs single-shot RAG vs agentic RAG

Everything is generated by this script, so no PDFs are needed:

  1. CORPUS     A made-up world (fictional institutes, projects, people, universities)
                is turned into ~44 short documents. Names are fictional, so no model
                can know the answers from training: it must use the documents.
  2. QUESTIONS  25 questions with known answers:
                  10 simple       answer is in one document
                  10 multi-hop    answer needs 2-3 documents chained together
                   5 unanswerable the information does not exist (a good system must abstain)
  3. SYSTEMS    closed   : LLM alone, no retrieval (sanity check: should fail answerable questions)
                single   : retrieve top-k once with the question, one LLM call
                agentic  : tool-calling agent from agentic_rag.py (web search off)
  4. JUDGE      a different LLM compares each answer with the known gold answer
                (for unanswerable questions: correct only if the system abstains)
  5. METRICS    accuracy (with 95% confidence interval), latency, token usage, cost in USD,
                and retrieval support recall (did the needed documents get retrieved?)

Usage
-----
    python rag_eval.py                      # full run
    python rag_eval.py --per-category 2     # quick smoke test (2 questions per category)
    python rag_eval.py --systems single,agentic
    python rag_eval.py --fresh              # ignore saved results and start again

Results are saved after every question, so if you hit a rate limit or close the window,
run the same command again and it resumes where it stopped.

Needs agentic_rag.py and single_shot_rag.py in the same folder, and a Groq key (see agentic_rag.py).
Output goes to results/seed<N>/ (corpus/, questions.json, results.jsonl, summary.md).
"""

